import assert from 'node:assert/strict';
import { createParentBehaviorDraft, readParentBehaviorRecords, recordsForParentChild, saveParentBehaviorRecord, todayForParentRecord } from './parentBehaviorRecords.ts';
const memory = new Map();
globalThis.window = { localStorage: { getItem: key => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, value) } };
const child = { name: '郑小磊', schoolCode: 'school-a', studentNo: '001' };
const draft = { ...createParentBehaviorDraft(), content: '主动收拾餐桌' };
assert.throws(() => saveParentBehaviorRecord(createParentBehaviorDraft(), child, 'parent-a', '妈妈'), /描述/);
assert.throws(() => saveParentBehaviorRecord({ ...draft, occurredOn: '2099-01-01' }, child, 'parent-a', '妈妈'), /日期/);
assert.throws(() => saveParentBehaviorRecord({ ...draft, occurredOn: '2026-02-30' }, child, 'parent-a', '妈妈'), /日期/);
assert.throws(() => saveParentBehaviorRecord({ ...draft, content: '字'.repeat(2001) }, child, 'parent-a', '妈妈'), /2000/);
assert.throws(() => saveParentBehaviorRecord({ ...draft, images: ['https://invalid.example/image.png'] }, child, 'parent-a', '妈妈'), /图片/);
saveParentBehaviorRecord(draft, { ...child, exchangePassword: 'do-not-copy', bankBalance: 100 }, 'parent-a', '妈妈');
saveParentBehaviorRecord({ ...draft, content: '完成阅读' }, { ...child, studentNo: '002' }, 'parent-a', '妈妈');
saveParentBehaviorRecord(draft, { ...child, schoolCode: 'school-b' }, 'parent-a', '妈妈');
saveParentBehaviorRecord(draft, child, 'parent-b', '爸爸');
const visible = recordsForParentChild(readParentBehaviorRecords(), 'parent-a', child);
assert.equal(visible.length, 1);
assert.equal(visible[0].content, '主动收拾餐桌');
assert.equal(visible[0].source, 'parent');
assert.deepEqual(visible[0].subject, child);
assert.equal(visible[0].occurredOn, todayForParentRecord());
assert.ok(!('score' in visible[0]) && !('coins' in visible[0]));
const saved = JSON.stringify(readParentBehaviorRecords());
window.localStorage.setItem = () => { throw new Error('QuotaExceededError'); };
assert.throws(() => saveParentBehaviorRecord(draft, child, 'parent-a', '妈妈'), /保存失败/);
assert.equal(JSON.stringify(readParentBehaviorRecords()), saved);
assert.equal(draft.content, '主动收拾餐桌');
console.log('家长记录：空内容与日期校验、跨家长/学校/孩子隔离、刷新读取和保存失败恢复通过。');
