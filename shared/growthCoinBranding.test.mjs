import assert from 'node:assert/strict';
import { COIN_ICON_PRESETS, DEFAULT_COIN_BRANDING, getCoinBrandTerms, validateCoinBranding } from './growthCoinBranding.ts';
import { readCoinBranding, saveCoinBranding, subscribeCoinBranding, updateCoinBranding } from './growthCoinBrandingStore.ts';

const memory = new Map([['student-balance', '320'], ['student-history', '[{"amount":10}]']]);
globalThis.localStorage = { getItem: key => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, value) };
globalThis.window = new EventTarget();
assert.deepEqual(readCoinBranding('school-a'), DEFAULT_COIN_BRANDING);
let events = 0;
const unsubscribe = subscribeCoinBranding('school-a', () => events++);
const own = { name: ' 向阳币 ', iconUrl: COIN_ICON_PRESETS[1].url };
saveCoinBranding('school-a', own);
assert.equal(readCoinBranding('school-a').name, '向阳币');
assert.equal(events, 1);
assert.equal(readCoinBranding('school-a'), readCoinBranding('school-a'), '同一快照引用稳定，避免React反复渲染');
assert.deepEqual(readCoinBranding('school-b'), DEFAULT_COIN_BRANDING, '学校之间不共享名称和图标');
saveCoinBranding('school-b', { name: '笋芽币', iconUrl: COIN_ICON_PRESETS[2].url });
assert.equal(events, 1, '其他学校更新不通知本校');
assert.equal(getCoinBrandTerms(readCoinBranding('school-b')).details, '笋芽币明细');
saveCoinBranding('school-star', { name: '星河币', iconUrl: COIN_ICON_PRESETS[3].url });
assert.equal(readCoinBranding('BS2024').name, '星河币', '家长演示学校编号映射到同一学校');
assert.equal(memory.get('student-balance'), '320');
assert.equal(memory.get('student-history'), '[{"amount":10}]');
assert.throws(() => validateCoinBranding({ ...own, name: ' ' }), /1至8/);
assert.throws(() => validateCoinBranding({ ...own, name: '一二三四五六七八九' }), /1至8/);
assert.throws(() => validateCoinBranding({ ...own, iconUrl: 'javascript:alert(1)' }), /请选择图标/);
assert.throws(() => validateCoinBranding({ ...own, iconUrl: 'data:image/svg+xml;base64,PHN2Zz4=' }), /请选择图标/);
assert.equal(validateCoinBranding({ ...own, iconUrl: 'data:image/png;base64,AAAA' }).iconUrl, 'data:image/png;base64,AAAA');
assert.equal(DEFAULT_COIN_BRANDING.iconUrl, '/assets/growth-coins/coin-star.png', '默认使用金色星星金币');
memory.set('school-growth-coin-branding:v1:school-legacy', JSON.stringify({ name: '向阳币', iconUrl: '/assets/coin.png' }));
assert.deepEqual(readCoinBranding('school-legacy'), { name: '向阳币', iconUrl: DEFAULT_COIN_BRANDING.iconUrl }, '旧蓝底金币自动升级，保留本校名称');
assert.equal(saveCoinBranding('school-legacy', { name: '向阳币', iconUrl: '/assets/coin.png' }).iconUrl, DEFAULT_COIN_BRANDING.iconUrl, '保存旧草稿也使用新默认图标');
for (const iconUrl of ['/assets/c4d_growth.png', '/assets/c4d_shop.png', '/assets/c4d_bank.png', '/assets/growth-coins/coin-sprout.png', '/assets/growth-coins/coin-sun.png', '/assets/growth-coins/coin-laurel.png', '/assets/growth-coins/icon-flower.png']) {
  assert.equal(validateCoinBranding({ name: '旧校币', iconUrl }).iconUrl, iconUrl, '旧图标继续兼容');
}
saveCoinBranding('school-a', DEFAULT_COIN_BRANDING);
assert.deepEqual(readCoinBranding('school-a'), DEFAULT_COIN_BRANDING, '可恢复默认');
unsubscribe();
updateCoinBranding('school-instant', { name: '云朵币' });
assert.equal(readCoinBranding('school-instant').name, '云朵币', '确认名称立即写入');
updateCoinBranding('school-instant', { iconUrl: COIN_ICON_PRESETS[2].url });
assert.deepEqual(readCoinBranding('school-instant'), { name: '云朵币', iconUrl: COIN_ICON_PRESETS[2].url }, '选择图标立即写入且保留名称');
updateCoinBranding('school-instant', { name: '小红花' });
assert.equal(readCoinBranding('school-instant').iconUrl, COIN_ICON_PRESETS[2].url, '单独改名称保留已选图标');
assert.throws(() => updateCoinBranding('school-instant', { name: ' ' }), /1至8/);
assert.equal(readCoinBranding('school-instant').name, '小红花', '非法名称不覆盖原值');
const customA = 'data:image/png;base64,AAAA';
const customB = 'data:image/png;base64,BBBB';
updateCoinBranding('school-custom', { iconUrl: customA });
assert.equal(readCoinBranding('school-custom').customIconUrl, customA, '上传图标同时保留为自定义选项');
updateCoinBranding('school-custom', { iconUrl: COIN_ICON_PRESETS[0].url });
assert.equal(readCoinBranding('school-custom').customIconUrl, customA, '切换预设仍保留自定义图标');
updateCoinBranding('school-custom', { name: '向阳币' });
assert.equal(readCoinBranding('school-custom').customIconUrl, customA, '名称更新不清除自定义图标');
updateCoinBranding('school-custom', { iconUrl: readCoinBranding('school-custom').customIconUrl });
assert.equal(readCoinBranding('school-custom').iconUrl, customA, '可重新应用自定义图标');
updateCoinBranding('school-custom', { iconUrl: customB });
assert.equal(readCoinBranding('school-custom').customIconUrl, customB, '仅保留最近一次上传');
assert.equal(readCoinBranding('school-b').customIconUrl, undefined, '上传图标按学校隔离');
memory.set('school-growth-coin-branding:v1:school-old-upload', JSON.stringify({ name: '旧校币', iconUrl: customA }));
assert.equal(readCoinBranding('school-old-upload').customIconUrl, customA, '旧数据读取时自动保留已上传图片');
updateCoinBranding('school-old-upload', { iconUrl: COIN_ICON_PRESETS[1].url });
assert.equal(readCoinBranding('school-old-upload').customIconUrl, customA, '旧数据切换预设仍保留上传图片');
assert.throws(() => updateCoinBranding('school-custom', { customIconUrl: 'javascript:alert(1)' }), /重新上传/);
assert.equal(readCoinBranding('school-custom').customIconUrl, customB, '非法替换不覆盖旧图');
localStorage.setItem = () => { throw new Error('quota'); };
assert.throws(() => saveCoinBranding('school-a', own), /保存失败/);
assert.throws(() => updateCoinBranding('school-custom', { iconUrl: customA }), /保存失败/);
assert.equal(readCoinBranding('school-custom').iconUrl, customB, '写入失败保留当前图标');
assert.equal(readCoinBranding('school-custom').customIconUrl, customB, '写入失败保留上传图标');
assert.deepEqual(readCoinBranding('school-a'), DEFAULT_COIN_BRANDING, '保存失败不能假报成功或改内存快照');
console.log('学校货币外观检查通过：学校隔离、跨端映射、校验、恢复默认、写入失败与旧资产保留');
