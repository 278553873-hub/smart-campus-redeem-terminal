import assert from 'node:assert/strict';
import { build } from 'esbuild';
const result = await build({ stdin: { resolveDir: process.cwd(), contents: `export * from './shared/classPetRoster'; export * from './shared/classPetSettings';` }, bundle: true, write: false, platform: 'node', format: 'esm' });
const api = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
const values = new Map();
globalThis.window = { localStorage: { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) }, dispatchEvent: () => {} };
const settings = { enabled: true, claimMethod: 'teacher', deductExperience: false, levelPoints: api.DEFAULT_PET_LEVEL_POINTS };
assert.throws(() => api.claimClassPetEggs('school', 'class', ['a']), /未开放/);
api.writeSchoolClassPetSettings('school', settings);
assert.throws(() => api.claimClassPetEggs('school', 'class', []), /暂无学生/);
const claimedAt = '2026-11-03T01:00:00.000Z';
const roster = api.claimClassPetEggs('school', 'class', ['a', 'b'], claimedAt);
assert.deepEqual(Object.keys(roster.students), ['a', 'b']);
assert.equal(api.readClassPetRoster('school', 'another'), null);
assert.equal(api.readClassPetRoster('another', 'class'), null);
assert.equal(api.claimClassPetEggs('school', 'class', ['a'], 'later').claimedAt, claimedAt);
const update = (id, score, recordedAt = '2026-11-03T02:00:00.000Z', remove = false) => api.updateClassPetEvaluation('school', 'class', ['a', 'b'], { id, score, recordedAt }, remove);
const growth = () => { const pet = api.readClassPetRoster('school', 'class').students.a; return api.getClaimedPetGrowth(pet.evaluations, api.readSchoolClassPetSettings('school'), pet.highestStage); };
update('history', 100, '2026-11-02T00:00:00.000Z');
assert.equal(growth().experience, 0, '领取前的历史评价不计入');
update('praise', 25); update('praise', 25);
assert.equal(growth().experience, 25, '相同记录回调不重复计入');
assert.equal(growth().stage, 2);
update('negative', -20);
assert.equal(growth().experience, 25, '默认不扣经验');
api.writeSchoolClassPetSettings('school', { ...settings, deductExperience: true });
assert.equal(growth().experience, 5);
assert.equal(growth().stage, 2, '扣分不得退阶段');
assert.equal(growth().level, 4);
update('praise', 0, undefined, true);
assert.equal(growth().experience, 0);
assert.equal(growth().stage, 2, '撤销评价也保留已生成形象');
const custom = api.getClaimedPetGrowth([{ id: 'x', score: 5 }], { ...settings, levelPoints: Array(9).fill(10) });
assert.equal(custom.level, 1, '使用学校的自定义门槛');
const before = api.readClassPetRoster('school', 'class');
window.localStorage.setItem = () => { throw new Error('存储不可用'); };
assert.throws(() => api.saveClassPetRoster('school', 'class', { ...before, view: 'student-info' }));
assert.equal(api.readClassPetRoster('school', 'class').view, 'pet');
console.log('班级领取：全班领取、学校/班级隔离、幂等、领取时间、扣分阶段保护、自定义经验及失败恢复通过');
