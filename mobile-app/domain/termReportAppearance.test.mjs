assert.deepEqual(getReportStages(['一年级', '二年级', '七年级']).map(stage => stage.id), ['primary-lower', 'junior']);
const fixed = { ...custom, artwork: 'preset', preset: { grade: '三年级', gender: 'female' } };
const fixedSchool = unifySchoolCover(config, fixed);
assert.deepEqual(resolveCoverStyle(fixedSchool, '一年级').preset, resolveCoverStyle(fixedSchool, '九年级').preset);
assert.ok(validateReportAppearance({ ...config, defaultCover: { ...fixed, preset: undefined } }));
