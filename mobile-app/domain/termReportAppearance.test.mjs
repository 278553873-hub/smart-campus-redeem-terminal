assert.ok(validateReportAppearance({ ...config, defaultCover: { ...ipStyle, imageId: 'missing' } }));
assert.ok(validateReportAppearance({ ...config, defaultCover: { ...custom, imageScale: NaN } }));
assert.ok(validateReportAppearance({ ...config, schoolName: '  ' }));
