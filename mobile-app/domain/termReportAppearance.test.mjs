import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
const load = async entry => {
  const { outputFiles } = await build({ entryPoints: [fileURLToPath(new URL(entry, import.meta.url))], bundle: true, write: false, platform: 'node', format: 'esm' });
  return import(`data:text/javascript;base64,${Buffer.from(outputFiles[0].text).toString('base64')}`);
};
const domain = await load('./termReportAppearance.ts');
const store = await load('../services/termReportAppearanceStore.ts');
const { createReportAppearance, resolveCoverStyle, setStageCover, followSchoolCover, copyCoverToStages, unifySchoolCover, validateReportAppearance, pruneCoverAssets, effectiveReportAppearance, getReportStages } = domain;
