config = copyCoverToStages(config, custom, ['primary-upper', 'junior']);
config = setStageCover(config, 'primary-middle', { ...custom, theme: 'violet' });
assert.equal(domain.resolveStageCover(config, 'primary-upper').theme, 'sage', '旧配置保留原数据');
assert.equal(resolveCoverStyle(config, '初一').theme, 'sand');
