import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { transform } from 'esbuild';

let cursor=0, dirty=false, tree, slots=[];
const same=(a,b)=>a&&b&&a.length===b.length&&a.every((v,i)=>Object.is(v,b[i]));
const useState=initial=>{
  const i=cursor++;
  if(!(i in slots)) slots[i]=typeof initial==='function'?initial():initial;
  return [slots[i],value=>{ slots[i]=typeof value==='function'?value(slots[i]):value; dirty=true; }];
};
const useRef=initial=>{const i=cursor++;return slots[i]??(slots[i]={current:initial});};
const useEffect=(effect,deps)=>{const i=cursor++;if(!same(slots[i]?.deps,deps)){slots[i]?.cleanup?.();slots[i]={deps,cleanup:effect()};}};
const React={createElement:(type,props,...children)=>({type,props:{...props,children}})};
let resetCount=0, values={};
const form={resetFields:()=>{resetCount++;values={};},setFieldsValue:patch=>{values={...values,...patch};}};
const Form=Object.assign(()=>{}, {useForm:()=>[form],Item:'item'});
const context=vm.createContext({React,useState,useRef,useEffect,Form,Input:Object.assign(()=>{},{Password:'password'}),Button:'button',ScreenPanoramaDialog:'dialog'});
const source=fs.readFileSync(new URL('StudentGrowthAccountDialog.tsx',import.meta.url),'utf8').replace(/^import .*;\n/gm,'').replaceAll('export ','');
vm.runInContext((await transform(source,{loader:'tsx',jsx:'transform'})).code,context);
vm.runInContext('globalThis.renderAccount=StudentGrowthAccountDialog;',context);
const nodes=value=>Array.isArray(value)?value.flatMap(nodes):value&&typeof value==='object'?[value,...nodes(value.props?.children)]:[];
const textOf=value=>Array.isArray(value)?value.map(textOf).join(''):value&&typeof value==='object'?textOf(value.props?.children):String(value??'');
const find=predicate=>nodes(tree).find(predicate);
let authenticate,closed=0;
const render=()=>{cursor=0;dirty=false;tree=context.renderAccount({onClose:()=>closed++,authenticate});};
const unmount=()=>{for(const slot of slots)slot?.cleanup?.();slots=[];};
const submit=async()=>{await find(n=>n.type===Form).props.onSubmit({account:' 20260101 ',password:'private-password'});render();};
render();
assert.ok(textOf(tree).includes('登录后，查看自己的积分和评价记录。'));
assert.ok(!textOf(tree).includes('123456'));
await submit();
assert.ok(textOf(tree).includes('暂时无法登录，请联系老师。'),'未接认证不允许假登录');
assert.equal(values.password,'');
assert.ok(!textOf(tree).includes('我的评价记录'));
authenticate=async()=>{throw Error('服务端私密错误详情');};
render();await submit();
assert.ok(textOf(tree).includes('请检查学号和密码'));
assert.ok(!textOf(tree).includes('服务端私密错误详情'));
let credentials;
authenticate=async input=>{credentials=input;return {studentId:'self',name:'陈子涵',className:'三年级2班',points:18,dimensions:[{name:'崇德',points:18}],records:[{id:'own-record',teacherName:'李敏',date:'11月16日',content:'本人的完整评价内容',points:-2}]};};
render();await submit();
assert.equal(credentials.account,'20260101');
assert.equal(credentials.password,'private-password');
assert.ok(textOf(tree).includes('陈子涵')&&textOf(tree).includes('本人的完整评价内容'));
assert.ok(textOf(tree).includes('-2分'));
assert.ok(!find(n=>n.type===Form),'认证后不继续保留密码输入表单');
assert.equal(tree.props.returnLabel,'退出并返回大屏');
tree.props.onClose();assert.equal(closed,1);
const resetBefore=resetCount;unmount();assert.ok(resetCount>resetBefore,'退出清理表单值');
render();assert.ok(!textOf(tree).includes('本人的完整评价内容'),'重新进入必须再次登录');
unmount();
let finish;
authenticate=()=>new Promise(resolve=>{finish=resolve;});
render();const pending=find(n=>n.type===Form).props.onSubmit({account:'a',password:'b'});
unmount();dirty=false;
finish({studentId:'self',name:'迟到的结果',className:'1班',points:1,dimensions:[],records:[]});
await pending;
assert.equal(dirty,false,'退出后异步认证结果不能恢复私人会话');
console.log('私人入口检查通过：未认证保持锁定、拒绝假登录、本人资料、退出清理及异步结果失效。');
